import type { AtomSite } from '@/core/crystallography/structure'

export interface SymOp {
  /** 3×3 rotation matrix (integer entries) */
  r: number[][]
  /** translation vector (fractional) */
  t: number[]
  /** original Seitz notation, for display */
  s?: string
}

export interface FractionalXYZ {
  x: number
  y: number
  z: number
}

const VARIABLE_INDEX: Record<string, number> = { x: 0, y: 1, z: 2 }

/** Parse a numeric literal such as 1/2, -0.25, 1/3, 2. */
export function parseRational(text: string): number {
  const t = text.trim()
  if (!t || t === '+' || t === '-') return t === '-' ? -1 : 1
  if (t.includes('/')) {
    const [num, den] = t.split('/')
    const n = Number(num)
    const d = Number(den)
    return Number.isFinite(n) && Number.isFinite(d) && d !== 0 ? n / d : 0
  }
  const v = Number(t)
  return Number.isFinite(v) ? v : 0
}

/**
 * Parse a symmetry operation in Seitz notation, e.g. "-x+1/2, y, -z+1/3".
 * Supports fractions, implicit coefficients (x, -y, 2x) and any term order.
 */
export function parseSymmetryOperation(seitz: string): SymOp {
  const cleaned = seitz
    .replace(/\u2212/g, '-')
    .replace(/\s+/g, '')
    .replace(/^['"]|['"]$/g, '')
  const parts = cleaned.split(',')
  if (parts.length !== 3) {
    throw new Error(`无法解析对称操作：${seitz}`)
  }
  const r: number[][] = [
    [0, 0, 0],
    [0, 0, 0],
    [0, 0, 0],
  ]
  const t = [0, 0, 0]
  parts.forEach((part, row) => {
    // Insert an explicit + before every - so terms can be split reliably.
    const normalized = part.replace(/-/g, '+-').replace(/^\+/, '')
    for (const term of normalized.split('+')) {
      if (!term) continue
      const variable = term.match(/[xyz]/i)
      if (variable) {
        const varName = variable[0].toLowerCase()
        const sign = term.startsWith('-') ? -1 : 1
        const withoutSign = term.replace(/^[+-]/, '')
        const coeffText = withoutSign.replace(/[xyz]/gi, '').replace(/\*/g, '')
        const coeff = coeffText === '' ? 1 : parseRational(coeffText)
        r[row][VARIABLE_INDEX[varName]] += sign * coeff
      } else {
        t[row] += parseRational(term)
      }
    }
  })
  return { r, t, s: seitz.trim() }
}

export function wrap01(value: number): number {
  const v = value % 1
  return v < 0 ? v + 1 : v
}

export function applySymOp(op: SymOp, xyz: FractionalXYZ): FractionalXYZ {
  const { r, t } = op
  return {
    x: wrap01(r[0][0] * xyz.x + r[0][1] * xyz.y + r[0][2] * xyz.z + t[0]),
    y: wrap01(r[1][0] * xyz.x + r[1][1] * xyz.y + r[1][2] * xyz.z + t[1]),
    z: wrap01(r[2][0] * xyz.x + r[2][1] * xyz.y + r[2][2] * xyz.z + t[2]),
  }
}

const IDENTITY: SymOp = {
  r: [
    [1, 0, 0],
    [0, 1, 0],
    [0, 0, 1],
  ],
  t: [0, 0, 0],
  s: 'x, y, z',
}

function coordinateKey(xyz: FractionalXYZ, decimals = 4): string {
  const scale = 10 ** decimals
  const q = (v: number) => {
    const wrapped = wrap01(v)
    const rounded = Math.round(wrapped * scale) % scale
    return rounded === scale ? 0 : rounded
  }
  return `${q(xyz.x)},${q(xyz.y)},${q(xyz.z)}`
}

/**
 * Expand asymmetric-unit atom sites into the full unit cell.
 * Duplicates are removed by element + fractional coordinate (4 decimals).
 */
export function expandAtoms(atoms: readonly AtomSite[], ops: readonly SymOp[]): AtomSite[] {
  const effectiveOps = ops.length ? ops : [IDENTITY]
  const seen = new Set<string>()
  const out: AtomSite[] = []
  for (const atom of atoms) {
    for (const op of effectiveOps) {
      const p = applySymOp(op, atom)
      const key = `${atom.element.toUpperCase()}|${coordinateKey(p)}`
      if (seen.has(key)) continue
      seen.add(key)
      out.push({
        ...atom,
        x: p.x,
        y: p.y,
        z: p.z,
      })
    }
  }
  out.sort(
    (a, b) =>
      a.element.localeCompare(b.element) ||
      a.x - b.x ||
      a.y - b.y ||
      a.z - b.z,
  )
  return out
}

/** Count distinct positions generated by a set of operations. */
export function orbitSize(ops: readonly SymOp[]): number {
  const seen = new Set<string>()
  for (const op of ops) {
    seen.add(coordinateKey(applySymOp(op, { x: 0.137, y: 0.281, z: 0.409 })))
  }
  return seen.size
}

export function opsFromSeitz(seitzList: readonly string[]): SymOp[] {
  return seitzList.map((s) => parseSymmetryOperation(s))
}
